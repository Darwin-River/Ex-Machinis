#!/usr/bin/env bash
#
# First-time setup for the Docker deployment. Run it from anywhere:
#
#   deploy/setup.sh                      # asks for the domain and admin email
#   deploy/setup.sh example.com you@example.com
#
# It writes deploy/.env (random passwords and keys), starts everything with
# Docker Compose and prints the DNS record to add. Running it again keeps the
# existing .env and just rebuilds and restarts. There is no email (#367).
set -euo pipefail

cd "$(dirname "$0")"

die() { echo "Error: $*" >&2; exit 1; }
command -v docker >/dev/null || die "Docker is not installed (see deploy/README.md)."
docker compose version >/dev/null 2>&1 || die "The Docker Compose plugin is not installed."
command -v openssl >/dev/null || die "openssl is required."

# --- Settings ---------------------------------------------------------------

if [ -f .env ]; then
    echo "Using the existing deploy/.env"
    set -a; . ./.env; set +a
else
    DOMAIN="${1:-${DOMAIN:-}}"
    ADMIN_EMAIL="${2:-${ADMIN_EMAIL:-}}"
    [ -n "$DOMAIN" ] || read -rp "Game domain (e.g. exmachinis.com): " DOMAIN
    [ -n "$ADMIN_EMAIL" ] || read -rp "Your email (Let's Encrypt notices): " ADMIN_EMAIL
    [[ "$DOMAIN" =~ ^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$ ]] || die "'$DOMAIN' doesn't look like a domain."
    [[ "$ADMIN_EMAIL" == *@*.* ]] || die "'$ADMIN_EMAIL' doesn't look like an email address."

    secret() { openssl rand -hex 24; }
    umask 077
    cat > .env <<EOF
# Generated by setup.sh on $(date -u +%F). Keep this file private and backed up:
# APP_KEY and the passwords can't be recovered from anywhere else.
DOMAIN=$DOMAIN
ADMIN_EMAIL=$ADMIN_EMAIL

APP_KEY=base64:$(openssl rand -base64 32)
CRON_KEY=$(secret)
DB_ROOT_PASSWORD=$(secret)
DB_PASSWORD=$(secret)

# Optional overrides
#SITE_ADDRESS=$DOMAIN, www.$DOMAIN   # extra names Caddy should serve
#APP_URL=https://$DOMAIN
${SITE_ADDRESS:+SITE_ADDRESS=$SITE_ADDRESS}

# Game time: game seconds per real second (60 = one real minute is one game
# hour) and drones' acceleration in m/s^2. See documents/design-manual.md.
#GAME_TIME_SCALE=60
#TRAVEL_ACCELERATION=1
${GAME_TIME_SCALE:+GAME_TIME_SCALE=$GAME_TIME_SCALE}
# The clock floor: the clock slows when the engines fall behind, never below
# this; behind at the floor, new releases queue. Public Forge: 24 and 8.
#GAME_TIME_FLOOR=0
${GAME_TIME_FLOOR:+GAME_TIME_FLOOR=$GAME_TIME_FLOOR}
# The engines' log detail: -1 (default) errors, warnings and clock changes
# only; 0 to 3 every step (gigabytes a day under load)
#ENGINE_TRACE_LEVEL=-1
${ENGINE_TRACE_LEVEL:+ENGINE_TRACE_LEVEL=$ENGINE_TRACE_LEVEL}
EOF
    umask 022
    echo "Wrote deploy/.env"
    set -a; . ./.env; set +a
fi

# --- Start ------------------------------------------------------------------

docker compose up -d --build

# --- DNS record -------------------------------------------------------------

cat <<EOF

Ex-Machinis is starting. Follow progress with:  cd deploy && docker compose logs -f

Add this DNS record for $DOMAIN (SERVER_IP = this server's public IP):

  $DOMAIN.                A     SERVER_IP

The website is https://$DOMAIN once DNS points here (Caddy gets the
certificate automatically). Secrets are in deploy/.env; back it up.
EOF
